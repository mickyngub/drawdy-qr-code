import typescript from "@rollup/plugin-typescript";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

function readWebviewJs() {
    return readFileSync(join(pkgRoot, "dist", "webview.js"), "utf8").replaceAll(
        "</script",
        "<\\/script"
    );
}

const STANDALONE_STYLING = [
    "color-scheme: light;",
    "--drawdy-background: #ffffff;",
    "--drawdy-foreground: #111111;",
    "--drawdy-surface: #fafafa;",
    "--drawdy-muted-foreground: #6b7280;",
    "--drawdy-primary: #4f46e5;",
    "--drawdy-primary-foreground: #ffffff;",
    "--drawdy-accent: #6366f1;",
    "--drawdy-border: #e5e7eb;",
    "--drawdy-destructive: #dc2626;",
    "--drawdy-success: #16a34a;",
    "--drawdy-radius-sm: 4px;",
    "--drawdy-radius-md: 8px;",
].join("");

function standaloneHtml() {
    return {
        name: "webview-standalone-html",
        writeBundle() {
            const shellPath = join(pkgRoot, "dist", "shell.cjs");
            delete require.cache[require.resolve(shellPath)];
            const { shellHtml } = require(shellPath);
            const unstyled = shellHtml(readWebviewJs());
            // Committed because the publishing service builds src/index.ts with
            // esbuild and runs no bundler plugins.
            const out = join(pkgRoot, "src", "webview-html.ts");
            const source =
                `// Generated by rollup.config.mjs. Do not edit by hand.\n` +
                `export const WEBVIEW_HTML = ${JSON.stringify(unstyled)};\n`;
            // Skipping identical writes keeps the dev server's rebuild-on-change from looping.
            if (!existsSync(out) || readFileSync(out, "utf8") !== source) writeFileSync(out, source);
            const html = unstyled.replace(
                "/*__DRAWDY_STYLING__*/",
                STANDALONE_STYLING
            );
            writeFileSync(
                join(pkgRoot, "dist", "webview-standalone.html"),
                html
            );
        },
    };
}

const webview = {
    input: "webview/main.ts",
    output: {
        file: "dist/webview.js",
        format: "iife",
    },
    plugins: [typescript({ tsconfig: join(pkgRoot, "tsconfig.json") })],
};

const shell = {
    input: "src/webview-shell.ts",
    output: {
        file: "dist/shell.cjs",
        format: "cjs",
        exports: "named",
    },
    plugins: [
        typescript({ tsconfig: join(pkgRoot, "tsconfig.json") }),
        standaloneHtml(),
    ],
};

const driver = {
    input: "src/index.ts",
    output: {
        file: "dist/main.js",
        format: "cjs",
        exports: "named",
    },
    plugins: [typescript({ tsconfig: join(pkgRoot, "tsconfig.json") })],
};

export default [webview, shell, driver];
